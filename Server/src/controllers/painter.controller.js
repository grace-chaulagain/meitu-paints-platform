// Admin: re-renders the ID card with an uploaded headshot composited in.
// The photo (req.file, multer memoryStorage - never touches disk) is used
// once to build the PDF and then discarded; see the service function's own
// comment for why nothing about the photo is ever persisted.
export const regeneratePainterIdCardWithPhotoController = asyncHandler(async (req, res) => {
  const { painterId } = req.params;
  const url = await painterService.regeneratePainterIdCardWithPhoto(painterId, req.file);
  res.status(200).json({ ok: true, url });
});

// Serves the real template SVG (unmodified) so the admin's photo-adjustment
// preview is backed by the actual design, not a hand-recreated approximation.
export const getPainterIdCardTemplateController = asyncHandler(async (req, res) => {
  res.type("image/svg+xml").send(getIdCardTemplateSvgRaw());
});

