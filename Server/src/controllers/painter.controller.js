// Dealer-facing: register a new RTP painter inline during redemption.
// Immediately active/earning-eligible - see plan doc for the fraud-risk
// tradeoff this accepts (mitigated by dealer-approval gating + attempt
// logging + admin suspend/blacklist power after the fact).
export const registerRtpPainterController = asyncHandler(async (req, res) => {
  const { name, citizenshipNumber, phones, address } = req.body || {};
  const out = await painterService.registerPainterAsDealer({
    name,
    citizenshipNumber,
    phones,
    address,
    actorUser: req.user,
  });
  res.status(201).json({ ok: true, ...out });
});
