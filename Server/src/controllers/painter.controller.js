// Admin: mints a fresh, short-lived Cloudinary download URL for the TTP
// card PDF and returns it as JSON (not a server-side redirect) - the route
// itself is Bearer-token authenticated, but the returned Cloudinary URL is
// separately signed, so the frontend does the final navigation/download
// directly against Cloudinary once it has the URL in hand.
export const getPainterIdCardDownloadUrlController = asyncHandler(async (req, res) => {
  const { painterId } = req.params;
  const url = await painterService.getPainterIdCardDownloadUrl(painterId);
  res.status(200).json({ ok: true, url });
});

