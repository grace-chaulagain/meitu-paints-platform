import { z } from "zod";
import { objectIdSchema, optionalTrimmedString, phoneSchema, trimmedString } from "./common.validation.js";

export const painterIdParamsSchema = z
  .object({
    painterId: objectIdSchema,
  })
  .strict();

// type + citizenshipNumber are both required: Meitu only has two painter
// classifications (no "unclassified" state for new painters), and
// citizenshipNumber is the same dedup key the dealer-facing RTP
// registration path already requires (registerRtpPainterBodySchema below),
// extended to this admin path too.
export const createPainterBodySchema = z
  .object({
    name: trimmedString(160),
    phones: z.array(phoneSchema).min(1, "At least one phone number is required").max(5),
    address: optionalTrimmedString(300),
    notes: optionalTrimmedString(1000),
    type: z.enum(["TTP", "RTP"]),
    citizenshipNumber: trimmedString(60),
  })
  .strict();

// citizenshipNumber can be edited later (a typo fix, or backfilling a
// legacy painter created before this field existed) but stays optional
// here - unlike creation, an edit must not be blocked just because an
// older record doesn't have one yet. `type` is deliberately not editable
// through this schema at all: it's set once at creation, and an RTP -> TTP
// change only ever happens through the dedicated promote action.
export const updatePainterBodySchema = z
  .object({
    name: trimmedString(160).optional(),
    phones: z.array(phoneSchema).min(1, "At least one phone number is required").max(5).optional(),
    address: optionalTrimmedString(300),
    notes: optionalTrimmedString(1000),
    citizenshipNumber: optionalTrimmedString(60),
  })
  .strict();

export const painterListQuerySchema = z
  .object({
    q: optionalTrimmedString(120),
    sort: z.enum(["name-asc", "name-desc", "recent", "oldest"]).optional(),
    type: z.enum(["ALL", "TTP", "RTP"]).optional(),
    page: z.coerce.number().int().min(1).max(10000).optional(),
    limit: z.coerce.number().int().min(1).max(1000).optional(),
  })
  .strict();

export const painterSalesQuerySchema = z
  .object({
    page: z.coerce.number().int().min(1).max(10000).optional(),
    limit: z.coerce.number().int().min(1).max(100).optional(),
    dealerId: objectIdSchema.optional(),
  })
  .strict();

// Dealer-facing search: TTP is looked up by licenseId, RTP by
// citizenshipNumber - exactly one of the two must be present depending on
// type. Results are masked before they ever leave the service layer.
export const painterSearchQuerySchema = z
  .object({
    type: z.enum(["TTP", "RTP"]),
    licenseId: optionalTrimmedString(60),
    citizenshipNumber: optionalTrimmedString(60),
  })
  .strict()
  .refine(
    (value) => (value.type === "TTP" ? Boolean(value.licenseId) : Boolean(value.citizenshipNumber)),
    {
      message: "licenseId is required for TTP search, citizenshipNumber is required for RTP search",
      path: ["type"],
    },
  );

export const registerRtpPainterBodySchema = z
  .object({
    name: trimmedString(160),
    citizenshipNumber: trimmedString(60),
    phones: z.array(phoneSchema).min(1, "At least one phone number is required").max(5),
    address: optionalTrimmedString(300),
  })
  .strict();

// licenseId is deliberately not accepted here - the permanent Painter ID is
// always generated by the system (see painter.service.js:generatePainterId),
// never supplied by the admin.
export const promotePainterBodySchema = z
  .object({
    licenseIssuedAt: z.coerce.date().optional(),
    licenseStatus: z.enum(["VALID", "EXPIRED", "REVOKED"]).optional(),
  })
  .strict();

export const painterPointsQuerySchema = z
  .object({
    page: z.coerce.number().int().min(1).max(10000).optional(),
    limit: z.coerce.number().int().min(1).max(100).optional(),
    from: z.coerce.date().optional(),
    to: z.coerce.date().optional(),
  })
  .strict();
